using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Tangent.Core;
using Tangent.Core.Binding;
using Tangent.Core.Ir;
using Tangent.Core.Text;

namespace Tangent.Generators;

/// <summary>
/// Emits <c>Tangent.Contracts</c>, one <c>const string</c> per declared contract, so
/// <c>[Tangent(Contracts.Controller)]</c> fails to compile on a typo without waiting for the analyzer.
/// Purely optional: the analyzer's TNG0001 remains the source of truth, and this generator reports no
/// diagnostics of its own.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class ContractConstantsGenerator : IIncrementalGenerator
{
    private const string MetadataKey = "build_metadata.AdditionalFiles.TangentContract";
    private const string Extension = ".tan";
    private const string HintName = "TangentContracts.g.cs";

    /// <inheritdoc/>
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        IncrementalValuesProvider<ContractFile?> files = context.AdditionalTextsProvider
            .Combine(context.AnalyzerConfigOptionsProvider)
            .Select(static (pair, cancellationToken) =>
            {
                AdditionalText file = pair.Left;
                if (!IsContractFile(file, pair.Right)) return null;
                SourceText? text = file.GetText(cancellationToken);
                return text is null ? null : new ContractFile(file.Path ?? string.Empty, text.ToString());
            })
            .Where(static file => file is not null);

        context.RegisterSourceOutput(files.Collect(), static (production, collected) => Emit(production, collected));
    }

    private static bool IsContractFile(AdditionalText file, AnalyzerConfigOptionsProvider options)
    {
        if (options.GetOptions(file).TryGetValue(MetadataKey, out string? value) &&
            value != null &&
            value.Equals("true", StringComparison.OrdinalIgnoreCase))
        {
            return true;
        }

        string path = file.Path;
        return path != null && path.EndsWith(Extension, StringComparison.OrdinalIgnoreCase);
    }

    private static void Emit(SourceProductionContext context, ImmutableArray<ContractFile?> files)
    {
        if (files.IsDefaultOrEmpty) return;

        var sources = new List<SourceFile>(files.Length);
        foreach (ContractFile? file in files)
        {
            if (file is not null) sources.Add(new SourceFile(file.Path, file.Text));
        }

        if (sources.Count == 0) return;

        sources.Sort(static (left, right) => string.CompareOrdinal(left.Path, right.Path));

        BindResult result = ModelLoader.Load(sources.ToArray());
        ArchitectureModel? model = result.Model;
        if (model is null) return;

        var names = new List<string>(model.Contracts.Length);
        for (int i = 0; i < model.Contracts.Length; i++)
        {
            string name = model.Text(model.Contracts[i].Name);
            if (name.Length > 0 && !names.Contains(name)) names.Add(name);
        }

        if (names.Count == 0) return;
        names.Sort(StringComparer.Ordinal);

        var builder = new StringBuilder();
        builder.Append("// <auto-generated/>\n");
        builder.Append("#nullable enable\n\n");
        builder.Append("namespace Tangent\n{\n");
        builder.Append("    /// <summary>The names of every contract declared in this solution's <c>.tangent</c> folder.</summary>\n");
        builder.Append("    internal static class Contracts\n    {\n");

        for (int i = 0; i < names.Count; i++)
        {
            builder.Append("        /// <summary>The <c>").Append(names[i]).Append("</c> contract.</summary>\n");
            builder.Append("        public const string ").Append(names[i]).Append(" = \"").Append(names[i]).Append("\";\n");
            if (i < names.Count - 1) builder.Append('\n');
        }

        builder.Append("    }\n}\n");

        context.AddSource(HintName, SourceText.From(builder.ToString(), Encoding.UTF8));
    }

    private sealed class ContractFile : IEquatable<ContractFile>
    {
        internal ContractFile(string path, string text)
        {
            Path = path;
            Text = text;
        }

        internal string Path { get; }

        internal string Text { get; }

        public bool Equals(ContractFile? other) =>
            other is not null &&
            string.Equals(Path, other.Path, StringComparison.Ordinal) &&
            string.Equals(Text, other.Text, StringComparison.Ordinal);

        public override bool Equals(object? obj) => Equals(obj as ContractFile);

        public override int GetHashCode()
        {
            unchecked { return (Path.GetHashCode() * 397) ^ Text.GetHashCode(); }
        }
    }
}
