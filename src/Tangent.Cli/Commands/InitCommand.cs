using System.Text;
using System.Text.RegularExpressions;

namespace Tangent.Cli.Commands;

/// <summary>
/// <c>tangent init</c>: writes a starting <c>.tangent/</c> folder. Layers come from the root namespace of
/// every project in the solution and start at <c>-> nothing</c>, because the only honest default is that
/// nothing may depend on anything until someone says so.
/// </summary>
public static class InitCommand
{
    /// <summary>Runs the command.</summary>
    public static int Run(string? path, bool force, CliConsole console)
    {
        Target? target = TargetLocator.Resolve(path, out string? error);
        if (target is null)
        {
            console.WriteError("error: " + error);
            return ExitCodes.LoadFailure;
        }

        string folder = Path.Combine(target.Root, TargetLocator.FolderName);
        string projectFile = Path.Combine(folder, "project.tan");
        string contractsFile = Path.Combine(folder, "contracts.tan");

        if (!force && (File.Exists(projectFile) || File.Exists(contractsFile)))
        {
            console.WriteError($"error: '{folder}' already exists. Pass --force to overwrite it.");
            return ExitCodes.LoadFailure;
        }

        IReadOnlyList<string> projectPaths = target.IsSolution
            ? TargetLocator.ProjectsOf(target.Path)
            : new[] { target.Path };

        if (projectPaths.Count == 0)
        {
            console.WriteError($"error: '{target.Path}' lists no C# projects to build layers from.");
            return ExitCodes.LoadFailure;
        }

        var namespaces = new List<string>();
        foreach (string project in projectPaths)
        {
            string ns = RootNamespaceOf(project);
            if (!namespaces.Contains(ns, StringComparer.Ordinal)) namespaces.Add(ns);
        }

        namespaces.Sort(StringComparer.Ordinal);

        Directory.CreateDirectory(folder);
        File.WriteAllText(projectFile, RenderProject(Path.GetFileNameWithoutExtension(target.Path), namespaces, target));
        File.WriteAllText(contractsFile, string.Empty);

        console.WriteLine($"Created {Path.Combine(TargetLocator.FolderName, "project.tan")} with {namespaces.Count} {(namespaces.Count == 1 ? "layer" : "layers")}.");
        console.WriteLine($"Created {Path.Combine(TargetLocator.FolderName, "contracts.tan")}.");
        console.WriteLine();
        console.WriteLine("Next: open project.tan, say which layers may depend on which, then run 'tangent check'.");
        return ExitCodes.Clean;
    }

    /// <summary>Renders <c>project.tan</c>. Public so the shape can be asserted without touching the disk.</summary>
    public static string RenderProject(string projectName, IReadOnlyList<string> rootNamespaces, Target target)
    {
        var names = new List<string>(rootNamespaces.Count);
        foreach (string ns in rootNamespaces) names.Add(LayerName(ns, rootNamespaces));

        int width = 0;
        foreach (string name in names) width = Math.Max(width, name.Length);

        var builder = new StringBuilder();
        builder.Append("// Generated by 'tangent init'. This is the shape of ").Append(projectName).Append(", as Tangent sees it.\n");
        builder.Append("// Every layer starts at `-> nothing`: nothing may depend on anything until you say so.\n");
        builder.Append("// Run `tangent check` to see what that costs, then open the direction up one line at a time.\n\n");

        builder.Append("project \"").Append(projectName).Append("\" {\n");
        if (HasSourceFolder(target)) builder.Append("    root: \"src/\"\n\n");

        for (int i = 0; i < names.Count; i++)
        {
            builder.Append("    layer ").Append(names[i].PadRight(width)).Append(" = ").Append(rootNamespaces[i]).Append(".**\n");
        }

        builder.Append('\n');
        for (int i = 0; i < names.Count; i++)
        {
            builder.Append("    ").Append(names[i].PadRight(width)).Append(" -> nothing\n");
        }

        builder.Append("}\n\n");

        builder.Append("// A contract is a named set of rules that every matching type must satisfy. Uncomment this\n");
        builder.Append("// one, point it at a namespace you actually have, and `tangent check` will start enforcing it.\n");
        builder.Append("//\n");
        builder.Append("// contract Controller {\n");
        builder.Append("//     match class in ").Append(rootNamespaces[0]).Append(".** where name ends with \"Controller\"\n");
        builder.Append("//\n");
        builder.Append("//     require sealed\n");
        builder.Append("//     methods where public {\n");
        builder.Append("//         require returns Task<*>\n");
        builder.Append("//     }\n");
        builder.Append("// }\n");

        return builder.ToString();
    }

    private static bool HasSourceFolder(Target target) =>
        Directory.Exists(Path.Combine(target.Root, "src"));

    private static string LayerName(string rootNamespace, IReadOnlyList<string> all)
    {
        int dot = rootNamespace.LastIndexOf('.');
        if (dot < 0) return rootNamespace;

        string last = rootNamespace[(dot + 1)..];

        int collisions = 0;
        foreach (string other in all)
        {
            int otherDot = other.LastIndexOf('.');
            string otherLast = otherDot < 0 ? other : other[(otherDot + 1)..];
            if (string.Equals(otherLast, last, StringComparison.Ordinal)) collisions++;
        }

        return collisions == 1 ? last : rootNamespace.Replace(".", string.Empty, StringComparison.Ordinal);
    }

    /// <summary>
    /// The project's root namespace: its <c>&lt;RootNamespace&gt;</c> when it declares one, otherwise the
    /// file name, which is what MSBuild itself defaults to.
    /// </summary>
    public static string RootNamespaceOf(string projectPath)
    {
        try
        {
            Match match = Regex.Match(
                File.ReadAllText(projectPath),
                @"<RootNamespace>\s*([^<\s]+)\s*</RootNamespace>",
                RegexOptions.CultureInvariant);

            if (match.Success && !match.Groups[1].Value.Contains('$', StringComparison.Ordinal))
            {
                return match.Groups[1].Value;
            }
        }
        catch (IOException)
        {
            // Fall through to the file name.
        }

        return Path.GetFileNameWithoutExtension(projectPath);
    }
}
