using System.Threading.Tasks;
using Xunit;

namespace Tangent.Analyzers.Tests;

public sealed class BindingTests
{
    private const string Contracts = """
contract Alpha {
    match: class in Sample.Api.**
    sealed
}

contract Beta {
    match: class in Sample.Nowhere.**
    require abstract
}

contract Gamma {
    match: class in Sample.Nowhere.**
    require internal
}

bind Sample.Api.Thing to Beta
""";

    [Fact]
    public async Task BindStatementWinsOverMatchClause()
    {
        // Beta (bound) requires abstract; Alpha's `sealed` must not apply.
        const string source = """
namespace Sample.Api;

public sealed class {|TNG0101:Thing|}
{
}
""";

        await Harness.AnalyzerAsync(Contracts, source);
    }

    [Fact]
    public async Task AttributeWinsOverBindStatement()
    {
        // Gamma (attribute) requires internal; neither Beta nor Alpha may apply.
        const string source = """
using Tangent;

namespace Sample.Api;

[Tangent("Gamma")]
public sealed class {|TNG0101:Thing|}
{
}
""";

        await Harness.AnalyzerAsync(Contracts, source);
    }

    [Fact]
    public async Task MatchClauseAppliesWhenNothingElseDoes()
    {
        const string source = """
namespace Sample.Api;

public class {|TNG0101:Other|}
{
}
""";

        // `bind Sample.Api.Thing to Beta` names a type this compilation does not contain.
        await Harness.AnalyzerAsync(Contracts, source, Harness.Contract("TNG1002", 16, 1, 16, 30));
    }

    [Fact]
    public async Task UnknownContractInAttributeIsAnErrorWithASuggestion()
    {
        const string contracts = """
contract Controller {
    match: class in Sample.Api.** where name ends with "Controller"
    sealed
}
""";

        const string source = """
using Tangent;

namespace Sample.Api;

[{|TNG0001:Tangent("Controler")|}]
public sealed class Legacy
{
}
""";

        await Harness.AnalyzerAsync(contracts, source);
    }

    [Fact]
    public async Task UnknownRuleIdInExemptionIsAnError()
    {
        const string contracts = """
contract Controller {
    match: class in Sample.Api.** where name ends with "Controller"
    sealed
}
""";

        const string source = """
using Tangent;

namespace Sample.Api;

[{|TNG0002:TangentExempt("legacy", Rule = "Controller/type/modifier#7")|}]
public class {|TNG0101:LegacyController|}
{
}
""";

        await Harness.AnalyzerAsync(contracts, source);
    }

    [Fact]
    public async Task TypesInPartialDeclarationsReportWhereTheMemberLives()
    {
        const string contracts = """
contract Controller {
    match: class in Sample.Api.** where name ends with "Controller"
    fields { require readonly }
}
""";

        const string first = """
namespace Sample.Api;

public partial class OrdersController
{
    private readonly int _a = 1;
}
""";

        const string second = """
namespace Sample.Api;

public partial class OrdersController
{
    private int {|TNG0101:_b|} = 2;
}
""";

        await Harness.AnalyzerAsync(
            contracts,
            new[] { ("First.cs", first), ("Second.cs", second) });
    }

    [Fact]
    public async Task GeneratedCodeIsNotAnalyzed()
    {
        const string contracts = """
contract Controller {
    match: class in Sample.Api.** where name ends with "Controller"
    sealed
}
""";

        const string generated = """
// <auto-generated/>
namespace Sample.Api;

public class ReportsController
{
}
""";

        await Harness.AnalyzerAsync(contracts, new[] { ("Reports.g.cs", generated) });
    }

    [Fact]
    public async Task NoContractFilesProducesNoDiagnostics()
    {
        const string source = """
namespace Sample.Api;

public class OrdersController
{
    public int Count() => 1;
}
""";

        await Harness.NoContractsAsync(source);
    }
}
