using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Text;
using System.Text.RegularExpressions;
using Tangent.Core.Text;

namespace Tangent.Benchmarks;

/// <summary>
/// The `.tan` corpora every benchmark runs over. The sample contracts in <c>samples/Orders/.tangent</c>
/// are copied next to the benchmark assembly by the project file and are the single source of truth; the
/// large file and the thirty-contract model are generated from them / from templates at startup so the
/// numbers do not drift when the samples are edited.
/// </summary>
internal static class ContractSources
{
    private static readonly Regex ContractName = new Regex(
        @"\b(contract|extends)\s+([A-Za-z_][A-Za-z0-9_]*)",
        RegexOptions.Compiled | RegexOptions.CultureInvariant);

    /// <summary>The order matters only for reproducibility; the binder is order-independent.</summary>
    private static readonly string[] SampleFileNames =
    {
        "project.tan",
        "controllers.tan",
        "entities.tan",
        "repositories.tan",
        "services.tan",
        "bindings.tan",
    };

    private static readonly Lazy<ImmutableArray<SourceFile>> LazySample = new(LoadSample);
    private static readonly Lazy<SourceFile> LazyLarge = new(BuildLarge);
    private static readonly Lazy<ImmutableArray<SourceFile>> LazyThirty = new(BuildThirtyContracts);

    /// <summary>The six sample contract files, verbatim.</summary>
    internal static ImmutableArray<SourceFile> Sample => LazySample.Value;

    /// <summary>One generated file of roughly 500 lines: the samples replicated with unique names.</summary>
    internal static SourceFile Large => LazyLarge.Value;

    /// <summary>A project block with six layers plus thirty generated contracts, some of them `extends`.</summary>
    internal static ImmutableArray<SourceFile> ThirtyContracts => LazyThirty.Value;

    /// <summary>Counts the lines in a piece of contract text, for the documentation table.</summary>
    internal static int LineCount(string text)
    {
        int lines = 1;
        for (int i = 0; i < text.Length; i++)
        {
            if (text[i] == '\n') lines++;
        }

        return lines;
    }

    private static ImmutableArray<SourceFile> LoadSample()
    {
        string directory = Path.Combine(AppContext.BaseDirectory, "contracts");
        var builder = ImmutableArray.CreateBuilder<SourceFile>(SampleFileNames.Length);
        foreach (string name in SampleFileNames)
        {
            string path = Path.Combine(directory, name);
            if (!File.Exists(path))
            {
                throw new FileNotFoundException(
                    $"The sample contracts were not copied to '{directory}'. Rebuild Tangent.Benchmarks.",
                    path);
            }

            builder.Add(new SourceFile(".tangent/" + name, File.ReadAllText(path)));
        }

        return builder.MoveToImmutable();
    }

    private static SourceFile BuildLarge()
    {
        ImmutableArray<SourceFile> sample = Sample;
        string project = TextOf(sample, "project.tan");

        var text = new StringBuilder(32 * 1024);
        text.Append("// Generated by Tangent.Benchmarks: the sample contracts replicated with unique names.\n\n");
        text.Append(project).Append('\n');

        // Replica 0 keeps the sample names so `bindings.tan` still resolves; later replicas are suffixed.
        for (int replica = 0; LineCount(text.ToString()) < 500; replica++)
        {
            string suffix = replica == 0 ? string.Empty : "_" + replica.ToString(System.Globalization.CultureInfo.InvariantCulture);
            AppendReplica(text, sample, suffix, includeBindings: replica == 0);
        }

        return new SourceFile(".tangent/generated-large.tan", text.ToString());
    }

    private static void AppendReplica(StringBuilder text, ImmutableArray<SourceFile> sample, string suffix, bool includeBindings)
    {
        foreach (string name in SampleFileNames)
        {
            if (name == "project.tan") continue;
            if (name == "bindings.tan" && !includeBindings) continue;

            string body = TextOf(sample, name);
            if (suffix.Length != 0)
            {
                body = ContractName.Replace(body, m => m.Groups[1].Value + " " + m.Groups[2].Value + suffix);
            }

            text.Append(body).Append('\n');
        }
    }

    private static string TextOf(ImmutableArray<SourceFile> files, string name)
    {
        for (int i = 0; i < files.Length; i++)
        {
            if (files[i].Path.EndsWith(name, StringComparison.Ordinal)) return files[i].Text;
        }

        throw new InvalidOperationException("Missing sample contract file: " + name);
    }

    private static ImmutableArray<SourceFile> BuildThirtyContracts()
    {
        const string Project = """
            project "Bench" {
                root: "src/"

                layer Api            = Bench.Api.**
                layer Application    = Bench.Application.**
                layer Domain         = Bench.Domain.**
                layer Infrastructure = Bench.Infrastructure.**
                layer Contracts      = Bench.Contracts.**
                layer Shared         = Bench.Shared.**

                Api            -> Application, Domain, Contracts, Shared
                Application    -> Domain, Contracts, Shared
                Infrastructure -> Application, Domain, Contracts, Shared
                Domain         -> Contracts, Shared
                Contracts      -> Shared
                Shared         -> nothing

                allow Bench.Shared.Primitives.**
            }
            """;

        var contracts = new StringBuilder(48 * 1024);
        contracts.Append("// Generated by Tangent.Benchmarks: thirty contracts of varied shape.\n\n");

        for (int i = 0; i < 30; i++)
        {
            contracts.Append(ContractText(i)).Append('\n');
        }

        return ImmutableArray.Create(
            new SourceFile(".tangent/bench-project.tan", Project),
            new SourceFile(".tangent/bench-contracts.tan", contracts.ToString()));
    }

    /// <summary>
    /// Five contract shapes, cycled. Every fifth contract extends the one before it, so the binder has to
    /// flatten and topologically order real `extends` chains.
    /// </summary>
    private static string ContractText(int index)
    {
        string n = index.ToString(System.Globalization.CultureInfo.InvariantCulture);
        string b = (index - 4).ToString(System.Globalization.CultureInfo.InvariantCulture);
        return (index % 5) switch
        {
            0 => $$"""
                contract Endpoint{{n}} {
                    match: class in Api where name ends with "Controller{{n}}"

                    inherits ApiControllerBase
                    sealed
                    attributes [ApiController], [Route(*)]

                    ctor {
                        require public
                        injects only IMediator, ILogger<*>
                        require each parameter assigned to private readonly field
                    }

                    methods where public {
                        returns Task<ActionResult<*>> | Task<IActionResult>
                        attributes [HttpGet | HttpPost | HttpPut | HttpDelete]
                        forbid new DbContext, new HttpClient
                    }

                    forbid using Bench.Infrastructure.**
                }
                """,

            1 => $$"""
                contract Entity{{n}} {
                    match: class in Bench.Domain.Entities.**

                    inherits Entity<*> | AggregateRoot<*>

                    properties {
                        forbid public set
                    }
                    fields { require private; require readonly; forbid static }
                    ctor { forbid public }

                    forbid using System.Data.**, Microsoft.**
                }
                """,

            2 => $$"""
                contract Store{{n}} {
                    match: class in Infrastructure where name ends with "Repository{{n}}"

                    implements I{Name}
                    interface I{Name} lives in Domain
                    sealed

                    ctor { injects only BenchDbContext }
                    methods where public { returns Task<*> }

                    forbid using Bench.Api.**
                }
                """,

            3 => $$"""
                contract Service{{n}} {
                    match: class in Bench.Domain.Services.** where name starts with "S{{n}}"

                    implements I{Name}
                    sealed
                    stateless
                    fields { require private; require readonly }
                    methods where public { forbid returns void }

                    forbid using Bench.Application.**, Bench.Infrastructure.**
                }
                """,

            _ => $$"""
                contract Handler{{n}} extends Endpoint{{b}} {
                    match: class in Application where name ends with "Handler{{n}}"

                    implements IRequestHandler<*, *>

                    ctor {
                        injects only IBenchRepository, IClock, IUserContext
                        require each parameter null-checked
                    }

                    methods where public { returns Task<*> }
                }
                """,
        };
    }
}
